#!/usr/bin/env bash
#
# 阿里云跳板机 (123.57.220.65) 公网直连反代配置 — erp.cnjinhu.top → GK9000
#
# 用途: 手机/平板不开 WireGuard、不关代理, 直接用 https://erp.cnjinhu.top 访问中控。
# 链路: 手机 → https://erp.cnjinhu.top (本机 nginx) → WireGuard 隧道 → GK9000
#       (10.66.66.3) 的 5173 (前端) / 3200 (API + WS)。
#
# 运行方式: root 登录跳板机 (阿里云控制台「远程连接」即可), 整段脚本粘贴执行。
# 幂等: 重复执行安全 — 只覆盖自己名下的 /etc/nginx/conf.d/erp-smart-control.conf。
#
# 前置条件 (脚本会逐项自检):
#   1. DNS: erp.cnjinhu.top A 记录 → 123.57.220.65 (阿里云 DNS 控制台配)
#   2. 本机能 ping 通 10.66.66.3 (WireGuard 隧道在线)
#   3. 证书: 优先复用已有 letsencrypt 证书; 没有则尝试 certbot 签发
#   4. 阿里云安全组放行 80/443 (主域 cnjinhu.top 已在用 https, 一般已放行)

set -uo pipefail

CONF=/etc/nginx/conf.d/erp-smart-control.conf
DOMAIN=erp.cnjinhu.top
GK=10.66.66.3

echo "==== 1. 前置自检 ===="

# DNS
DNS_IP=$(getent hosts "$DOMAIN" | awk '{print $1}' | head -1 || true)
echo "DNS $DOMAIN → ${DNS_IP:-未解析}"
if [ -z "$DNS_IP" ]; then
  echo "⚠️ $DOMAIN 没有 DNS 解析 — 去阿里云 DNS 控制台给 cnjinhu.top 加 A 记录:"
  echo "   主机记录=erp  记录值=123.57.220.65  然后重跑本脚本"
  exit 1
fi

# WireGuard 隧道
if ping -c 2 -W 3 "$GK" >/dev/null 2>&1; then
  echo "WireGuard → GK9000 ($GK) 连通 ✓"
else
  echo "⚠️ ping 不通 $GK — WireGuard 隧道不在线, 检查 wg show / systemctl status wg-quick@*"
  exit 1
fi

# nginx
if ! command -v nginx >/dev/null 2>&1; then
  echo "nginx 未安装, 尝试安装..."
  (command -v dnf >/dev/null && dnf install -y nginx) || \
  (command -v yum >/dev/null && yum install -y nginx) || \
  (command -v apt-get >/dev/null && apt-get update -qq && apt-get install -y nginx) || {
    echo "⚠️ nginx 安装失败, 手动装好后重跑"; exit 1; }
fi
echo "nginx $(nginx -v 2>&1 | grep -o '[0-9.]*' | head -1) ✓"

echo ""
echo "==== 2. 找证书 ===="
CERT=""; KEY=""
# 2a-0. DNS 方式签发的证书 (aliyun-erp-cert-dns.sh 装到这里) — 优先
if [ -f "/etc/nginx/certs/$DOMAIN.fullchain.pem" ]; then
  CERT="/etc/nginx/certs/$DOMAIN.fullchain.pem"
  KEY="/etc/nginx/certs/$DOMAIN.key.pem"
  echo "复用 DNS 签发证书: $CERT"
fi
# 2a. 专属证书
if [ -z "$CERT" ] && [ -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem" ]; then
  CERT="/etc/letsencrypt/live/$DOMAIN/fullchain.pem"
  KEY="/etc/letsencrypt/live/$DOMAIN/privkey.pem"
  echo "复用已有证书: $CERT"
fi
# 2b. 已有 nginx 配置里 erp 用过的证书
if [ -z "$CERT" ]; then
  OLD_CERT=$(grep -rlE "server_name[^;]*$DOMAIN" /etc/nginx 2>/dev/null \
    | xargs -r grep -hE '^\s*ssl_certificate\s' 2>/dev/null | head -1 | awk '{print $2}' | tr -d ';')
  OLD_KEY=$(grep -rlE "server_name[^;]*$DOMAIN" /etc/nginx 2>/dev/null \
    | xargs -r grep -hE '^\s*ssl_certificate_key\s' 2>/dev/null | head -1 | awk '{print $2}' | tr -d ';')
  if [ -n "$OLD_CERT" ] && [ -f "$OLD_CERT" ]; then
    CERT="$OLD_CERT"; KEY="$OLD_KEY"
    echo "复用旧 erp 配置里的证书: $CERT"
  fi
fi
# 2c. certbot 签发
if [ -z "$CERT" ]; then
  command -v certbot >/dev/null 2>&1 || \
    (command -v dnf >/dev/null && dnf install -y certbot python3-certbot-nginx) || \
    (command -v yum >/dev/null && yum install -y certbot python3-certbot-nginx) || \
    (command -v apt-get >/dev/null && apt-get install -y certbot python3-certbot-nginx) || true
  if command -v certbot >/dev/null 2>&1; then
    echo "尝试 certbot 签发 $DOMAIN 证书 (走已运行的 nginx)..."
    certbot certonly --nginx -d "$DOMAIN" --non-interactive --agree-tos \
      --register-unsafely-without-email && {
      CERT="/etc/letsencrypt/live/$DOMAIN/fullchain.pem"
      KEY="/etc/letsencrypt/live/$DOMAIN/privkey.pem"
    }
  fi
fi
if [ -z "$CERT" ]; then
  echo "⚠️ 拿不到证书 — 先配 HTTP(80) 应急, 之后手动补证书再重跑本脚本换 HTTPS"
fi

echo ""
echo "==== 3. 写 nginx 配置 ($CONF) ===="
[ -f "$CONF" ] && cp "$CONF" "$CONF.bak.$(date +%Y%m%d%H%M%S)" && echo "旧配置已备份"

COMMON_PROXY=$(cat <<'EOF'
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
EOF
)

if [ -n "$CERT" ]; then
cat > "$CONF" <<EOF
# erp.cnjinhu.top → GK9000 智慧展厅中控 公网直连 (auto-generated by aliyun-public-proxy.sh)
limit_req_zone \$binary_remote_addr zone=scLogin:1m rate=10r/m;

server {
  listen 80;
  server_name $DOMAIN;
  location /.well-known/acme-challenge/ { root /var/www/html; }
  location / { return 301 https://\$host\$request_uri; }
}

server {
  listen 443 ssl http2;
  listen 8443 ssl http2;   # 备用端口: 若 443 被阿里云备案拦截, App 改用 https://$DOMAIN:8443
  server_name $DOMAIN;
  ssl_certificate     $CERT;
  ssl_certificate_key $KEY;

  client_max_body_size 2g;          # 媒体库大文件上传
  proxy_connect_timeout 10s;
  proxy_read_timeout  300s;
  proxy_send_timeout  300s;

  # 登录口第二层限流 (backend 自身也有 10次/分钟/IP)
  location = /api/client-auth/login {
    limit_req zone=scLogin burst=5 nodelay;
    proxy_pass http://$GK:3200;
$COMMON_PROXY
  }
  location = /api/admin/auth/login {
    limit_req zone=scLogin burst=5 nodelay;
    proxy_pass http://$GK:3200;
$COMMON_PROXY
  }

  # API
  location /api/ {
    proxy_pass http://$GK:3200;
$COMMON_PROXY
  }

  # WebSocket 状态推送
  location /ws/ {
    proxy_pass http://$GK:3200;
    proxy_http_version 1.1;
    proxy_set_header Upgrade \$http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_read_timeout 1h;
$COMMON_PROXY
  }

  # 前端 PWA (/control/)
  location / {
    proxy_pass http://$GK:5173;
$COMMON_PROXY
  }
}
EOF
else
cat > "$CONF" <<EOF
# erp.cnjinhu.top → GK9000 (HTTP 应急版 — 没证书, 补上后重跑脚本换 HTTPS)
limit_req_zone \$binary_remote_addr zone=scLogin:1m rate=10r/m;

server {
  listen 80;
  server_name $DOMAIN;
  client_max_body_size 2g;
  proxy_connect_timeout 10s;
  proxy_read_timeout 300s;

  location = /api/client-auth/login { limit_req zone=scLogin burst=5 nodelay; proxy_pass http://$GK:3200;
$COMMON_PROXY
  }
  location = /api/admin/auth/login { limit_req zone=scLogin burst=5 nodelay; proxy_pass http://$GK:3200;
$COMMON_PROXY
  }
  location /api/ { proxy_pass http://$GK:3200;
$COMMON_PROXY
  }
  location /ws/ {
    proxy_pass http://$GK:3200;
    proxy_http_version 1.1;
    proxy_set_header Upgrade \$http_upgrade;
    proxy_set_header Connection "upgrade";
    proxy_read_timeout 1h;
$COMMON_PROXY
  }
  location / { proxy_pass http://$GK:5173;
$COMMON_PROXY
  }
}
EOF
fi

echo ""
echo "==== 4. 生效 + 自测 ===="
nginx -t || { echo "⚠️ nginx 配置检查失败, 已写入的配置在 $CONF, 旧备份同目录"; exit 1; }
systemctl reload nginx 2>/dev/null || nginx -s reload
echo "nginx 已重载 ✓"

sleep 1
SCHEME=$([ -n "$CERT" ] && echo https || echo http)
echo "--- $SCHEME://$DOMAIN/api/system/health ---"
curl -sk -m 10 "$SCHEME://127.0.0.1/api/system/health" -H "Host: $DOMAIN" | head -c 300; echo ""
echo "--- $SCHEME://$DOMAIN/control/ (前端) ---"
curl -sk -m 10 -o /dev/null -w "HTTP %{http_code}\n" "$SCHEME://127.0.0.1/control/" -H "Host: $DOMAIN"

echo ""
echo "==== 完成 ===="
echo "手机不开 WireGuard 直接访问: $SCHEME://$DOMAIN/control/"
echo "App 服务器设置里「远程地址」填: $SCHEME://$DOMAIN"
echo ""
echo "⚠️ 若手机打开显示阿里云「未备案」拦截页 (本机是大陆 ECS, 443 端口查备案):"
echo "   安全组放行 8443, App 远程地址改填 https://$DOMAIN:8443 (已同时监听)"
