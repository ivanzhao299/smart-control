// Zero-dependency bundle for the two deliberately simple local source modules.
// Classic scripts load inside PlayerPage's opaque-origin sandbox without
// weakening its sandbox policy or requiring CORS on the static asset server.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../../frontend/public/park-ops');
const model = fs.readFileSync(path.join(root, 'ops-data-model.mjs'), 'utf8');
const content = fs.readFileSync(path.join(root, 'ops-content.mjs'), 'utf8');
const importLine = "import { defaults, fields, copyFields, validate, displayValue, apiURL, STORAGE_KEY } from './ops-data-model.mjs';\n";
assert.ok(content.startsWith(importLine), 'Unexpected module graph; update bundler explicitly');
const body = model.replace(/^export (const|function) /gm, '$1 ') + '\n' + content.slice(importLine.length);
const result = '// Generated by tools/park-ops/build-content.cjs. Do not edit directly.\n(() => {\n\'use strict\';\n' + body + '\n})();\n';
new vm.Script(result, { filename: 'ops-content.js' });
const output = path.join(root, 'ops-content.js');
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(output, 'utf8'), result, 'Stale business bundle: run node tools/park-ops/build-content.cjs');
  console.log('Park business bundle matches its reviewed source modules.');
} else { fs.writeFileSync(output, result); console.log('Generated ' + output); }
